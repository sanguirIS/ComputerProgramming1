/**
 * Shapes.java
 *
 * Draws different shapes (square, triangle, diamond, and oval)
 * using asterisks (*) and println() statements.
 */
public class Shapes {

    public static void main(String[] args) {
        // Square
        System.out.println("Square:");
        System.out.println("********");
        System.out.println("*      *");
        System.out.println("*      *");
        System.out.println("*      *");
        System.out.println("*      *");
        System.out.println("********");
        System.out.println();

        // Triangle
        System.out.println("Triangle:");
        System.out.println("   *   ");
        System.out.println("  ***  ");
        System.out.println(" ***** ");
        System.out.println("*******");
        System.out.println();

        // Diamond
        System.out.println("Diamond:");
        System.out.println("   *   ");
        System.out.println("  ***  ");
        System.out.println(" ***** ");
        System.out.println("*******");
        System.out.println(" ***** ");
        System.out.println("  ***  ");
        System.out.println("   *   ");
        System.out.println();

        // Oval
        System.out.println("Oval:");
        System.out.println("  ***  ");
        System.out.println(" *   * ");
        System.out.println("*     *");
        System.out.println("*     *");
        System.out.println(" *   * ");
        System.out.println("  ***  ");
    }
}
