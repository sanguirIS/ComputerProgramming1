/**
 * FavoriteSong.java
 *
 * Displays at least four (4) lines of a favorite song.
 * Each lyric is printed on its own line using println().
 */
public class FavoriteSong {

    public static void main(String[] args) {
        // Print four lines of the song, one line at a time.
        System.out.println("PANGINOON ANG NGALAN MO");
        System.out.println("KAGANDAHAN MO AY PAGMASDAN");
        System.out.println("SA IYO LAMANG MATATAGPUAN");
        System.out.println("SA IYO LAMANG");
    }
}
